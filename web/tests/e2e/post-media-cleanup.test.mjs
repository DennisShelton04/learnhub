import { UPLOADS_DIR } from "./helpers.mjs";
import { readdirSync } from "node:fs";
import { browser, check, createCommunity, live, newUser, shareNote, summary, T } from "./helpers.mjs";
const DIR = UPLOADS_DIR;
const count = () => readdirSync(DIR).length;
const o = await newUser("Orphan");
const c = await createCommunity(o, `Orphan ${T}`);
await shareNote(o, c, "Voice thread");
await live(o);
await o.getByRole("button", { name: "Record voice note" }).click();
await o.waitForTimeout(1500);
await o.getByRole("button", { name: "Send voice note" }).click();
await o.getByRole("button", { name: "Play voice note" }).waitFor();
const before = count();
await o.getByRole("button", { name: /Delete post/ }).click();
await o.waitForURL(c);
check("deleting a post removes its voice-note files", count() === before - 1, `${before} -> ${count()}`);
await browser.close();
summary();
